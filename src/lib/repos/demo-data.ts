// Image builder

let imgCounter = 0;
function galleryImages(
  businessId: string,
  placeId: string,
  urls: string[],
  storageStatus: BusinessImage["storageStatus"] = "external_only",
): BusinessImage[] {
  return urls.map((url, idx) => ({
    id: `img-${businessId}-${idx}-${++imgCounter}`,
    businessId,
    placeId,
    sourceUrl: url,
    r2Key: null,
    r2Url: null,
    storageStatus,
    imageType: idx === 0 ? "cover" : "gallery",
    isCover: idx === 0,
    sortOrder: idx,
    width: 1200,
    height: 800,
    alt: undefined,
  }));
}

