// helpers

interface WeeklyOpts {
  open: string;
  close: string;
  closedDays?: number[];
  allDay?: boolean;
}
function weeklyHours(opts: WeeklyOpts) {
  const days = [0, 1, 2, 3, 4, 5, 6];
  const closed = new Set(opts.closedDays ?? []);
  return days.map((dayOfWeek, idx) => ({
    dayOfWeek,
    openTime: closed.has(dayOfWeek) ? null : opts.open,
    closeTime: closed.has(dayOfWeek) ? null : opts.close,
    isClosed: closed.has(dayOfWeek),
    rawValue: opts.allDay ? "24 hours" : undefined,
    sortOrder: idx,
  }));
}
